import Foundation
import MLXLMCommon
import MLXLMServer

/// Per-request Super output: the reference reasoning channel, native tool
/// frames and the shared tool/structured-output validators. Streaming exposes
/// reasoning and plain content as they arrive. Tool calls (`auto` and forced)
/// stream to a client that streams, as on the scheduler's path
/// (`NativeToolStreamRouter`): the name, then argument fragments, each call
/// checked when its frame closes, one that fails after it started refused,
/// forced answers calls only. Otherwise (a client that does not stream, a
/// JSON response format, `DARKBLOOM_TTFT_STREAM_NATIVE_TOOL_CALLS` off, or
/// `DARKBLOOM_TTFT_STREAM_FORCED_TOOL_CALLS` off for a forced choice) tool
/// calls, forced-tool output and JSON content are withheld until validation.
/// A complete response is split once at the end, as the reference
/// non-streaming parser does. Total generated bytes are bounded. Grants no
/// sampler grammar or tool execution.
struct NemotronSuperLocalOutput {
    enum Failure: Error { case invalidRequest, limit, alreadyFinished, malformedToolFrame }

    struct Result: Equatable {
        let content: String
        let reasoning: String?
        let calls: [ToolCall]
    }

    let plan: NemotronSuperRequestPlan
    let streaming: Bool
    /// Nil when content carries no tool frames to parse.
    private let handler: BatchedToolStreamHandler?
    /// Streamed calls: content passes this router (no channel of its own),
    /// which exposes calls while generated. Nil withholds them.
    private var callRouter: NativeToolStreamRouter?
    private var channel: NemotronSuperReasoningChannel
    private var raw = ""
    private var content = ""
    private var reasoning = ""
    private var receivedBytes = 0
    private var finished = false
    private let maximumBytes: Int

    init(plan: NemotronSuperRequestPlan, streaming: Bool, maximumBytes: Int = 1 << 20,
         streamNativeToolCalls: Bool = ToolStreamPreparation.streamsNativeToolCallsByDefault,
         streamForcedToolCalls: Bool = ToolStreamPreparation.streamsForcedToolCallsByDefault.native) throws {
        guard maximumBytes > 0, maximumBytes <= 16 << 20 else { throw Failure.invalidRequest }
        self.plan = plan
        self.streaming = streaming
        // With no tool declared under auto choice the prompt offers no tools,
        // so a literal `<tool_call>` is answer text, as in the reference
        // server. Otherwise frames always parse: a call that `none` or the
        // declarations do not allow fails validation instead of reaching the
        // client as raw XML.
        let offersNoTools = plan.toolPolicy.mode == .auto && plan.toolPolicy.tools?.isEmpty != false
        let streamsCalls = streaming && streamNativeToolCalls && ToolStreamPreparation.streamsToolCallsByDefault
            && plan.toolPolicy.clientStreams && plan.request.streamToolCallDeltas && plan.toolPolicy.mode != .none
            && plan.request.responseFormat?.requiresJSONOutput != true && !offersNoTools
            && (streamForcedToolCalls || !plan.toolPolicy.requiresToolCall)
        let allowed = plan.toolPolicy.allowedToolNames
        handler = offersNoTools ? nil : BatchedToolStreamHandler(format: .nemotron,
            tools: plan.toolPolicy.tools?.map { $0.toolSpec() },
            streaming: streamsCalls ? ToolCallStreamingOptions(exposesName: { allowed.contains($0) }) : nil)
        if streamsCalls {
            callRouter = NativeToolStreamRouter(handler: handler, requiresToolCall: plan.toolPolicy.requiresToolCall,
                nativePrefix: nil, streamedCalls: plan.toolPolicy)
        }
        channel = NemotronSuperReasoningChannel(controls: plan.controls)
        self.maximumBytes = maximumBytes
    }

    private var withholdsContent: Bool {
        plan.toolPolicy.requiresToolCall || plan.request.responseFormat?.requiresJSONOutput == true
    }

    /// Events safe to expose now; empty while buffering.
    mutating func append(_ chunk: String) throws -> [MLXServerGenerationEvent] {
        guard !finished else { throw Failure.alreadyFinished }
        guard chunk.utf8.count <= maximumBytes - receivedBytes else {
            finished = true; throw Failure.limit
        }
        receivedBytes += chunk.utf8.count
        guard streaming else { raw += chunk; return [] }
        do { return try route(channel.stream(chunk)) }
        catch { finished = true; throw error }
    }

    /// Remaining events, then validated tool calls; nothing is exposed if
    /// validation fails. `cutAtLimit`: the engine cut the answer at the token
    /// limit and it ends as `length` (`TokenLimitCutPolicy`): an unfinished
    /// frame is dropped, calls that fail their checks are dropped
    /// (`ToolConstraintValidation.validateWithheld`), and a withheld
    /// structured answer leaves as generated. `truncated`: the answer stopped
    /// at the token limit (`length`), cut or not; a streamed call it left
    /// open stays truncated, as on the scheduler's streamed terminal.
    mutating func finish(cutAtLimit: Bool = false, truncated: Bool? = nil) throws
        -> (events: [MLXServerGenerationEvent], result: Result)
    {
        guard !finished else { throw Failure.alreadyFinished }
        finished = true
        var events: [MLXServerGenerationEvent] = []
        if streaming {
            events = try route(channel.finishStream())
            // The streamed reasoning stays; its copy is content and passes the
            // same tool and response-format checks as any other. A thought the
            // limit cut is not an answer: nothing is promoted.
            if channel.promotesUnterminatedReasoning, !reasoning.isEmpty, !cutAtLimit {
                events += try route([.init(content: reasoning, reasoningContent: nil)])
            }
        } else {
            let split = channel.complete(raw, promoting: !cutAtLimit)
            reasoning = split.reasoning ?? ""
            _ = try route([.init(content: split.content ?? "", reasoningContent: nil)])
        }
        if var router = callRouter {
            // As the scheduler's streamed terminal: settle a call closed by a
            // stop token, then re-check the whole set. A cut leaves an exposed
            // call open, unclosed, and the answer ends `length`.
            router.responseStarted = router.responseStarted || !events.isEmpty
            var settled = try router.finishToolCalls(truncated: truncated ?? cutAtLimit, cutAtLimit: cutAtLimit)
            // As the withheld path below: route refused mid-stream parse
            // failures, so one here is the end-of-stream remainder. A frame
            // left open is refused, or dropped at a cut; a bare `<to…` prefix
            // was only held while being probed and stays text.
            let tail = settled.reduce(into: "") { if case .content(let text) = $1 { $0 += text } }
            if Self.leavesUnterminatedFrame(handler, residual: tail) {
                guard cutAtLimit else { throw Failure.malformedToolFrame }
                settled.removeAll { if case .content = $0 { true } else { false } }
            }
            events += absorb(settled)
            if !(cutAtLimit && plan.toolPolicy.requiresToolCall) {
                try ToolConstraintValidation.validate(router.completedToolCalls, prepared: plan.toolPolicy,
                    responseStarted: router.responseStarted)
            }
            callRouter = router
            let validatedReasoning = reasoning.isEmpty ? nil : reasoning
            return (events, Result(content: content, reasoning: validatedReasoning, calls: router.completedToolCalls))
        }
        var calls = ParallelToolCallPolicy.admitted(handler?.finish() ?? [], prepared: plan.toolPolicy)
        var residual = handler?.takeResidualText() ?? ""
        let forced = plan.toolPolicy.requiresToolCall
        // route refuses mid-stream parse failures, so any failure here is the
        // end-of-stream remainder: a complete opening tag is an unterminated
        // frame; a bare `<to…` prefix was only withheld while being probed.
        if Self.leavesUnterminatedFrame(handler, residual: residual) || (forced && !ToolChoiceEnforcementPolicy.isFramingWhitespace(residual)) {
            guard cutAtLimit else { throw Failure.malformedToolFrame }
            residual = ""
        }
        try ToolConstraintValidation.validateWithheld(&calls, prepared: plan.toolPolicy, cutAtLimit: cutAtLimit)
        // A response format shapes the final answer; a turn that calls tools
        // is not one, so its text (none for a forced choice) passes unchanged.
        let text = forced ? "" : content + residual
        let validatedContent: String
        do {
            validatedContent = calls.isEmpty
                ? try OpenAIResponseFormatSupport.normalizedContent(text, for: plan.request.responseFormat)
                : text
        } catch {
            guard cutAtLimit else { throw error }
            validatedContent = text
        }
        let validatedReasoning = reasoning.isEmpty ? nil : reasoning
        // Streamed reasoning and plain streamed content (never JSON-normalized)
        // already left through route; only the parser's residual text remains.
        let pending = streaming && !withholdsContent ? residual : validatedContent
        let pendingReasoning = streaming ? nil : validatedReasoning
        if !pending.isEmpty || pendingReasoning != nil {
            events.append(.parsed(.init(content: pending, reasoningContent: pendingReasoning)))
        }
        events += calls.map { .toolCall($0) }
        return (events, Result(content: validatedContent, reasoning: validatedReasoning, calls: calls))
    }

    /// Reasoning is never parsed for tools; content passes the tool parser
    /// when the request has one.
    private mutating func route(_ pieces: [ParsedReasoning]) throws -> [MLXServerGenerationEvent] {
        var events: [MLXServerGenerationEvent] = []
        for piece in pieces {
            if let text = piece.reasoningContent, !text.isEmpty {
                reasoning += text
                events.append(.parsed(.init(content: "", reasoningContent: text)))
            }
            if var router = callRouter {
                guard !piece.content.isEmpty else { continue }
                router.responseStarted = router.responseStarted || !events.isEmpty
                let routed = try router.process(piece.content)
                // The shared parser returns a frame that failed before any of
                // it was exposed as text (a JSON-dialect frame, say): refuse
                // it before this chunk leaves, as the withheld path does. One
                // that failed after it started was refused with its check.
                guard (handler?.parseFailureCount ?? 0) == 0 else { throw Failure.malformedToolFrame }
                events += absorb(routed)
                callRouter = router
                continue
            }
            var visible = ""
            if let handler {
                for segment in Self.tagSegments(piece.content) {
                    let text = handler.processChunk(segment)
                    // The shared parser returns a failed frame as text; refuse
                    // it before that text can be exposed.
                    guard handler.parseFailureCount == 0 else { throw Failure.malformedToolFrame }
                    visible += text ?? ""
                }
            } else {
                visible = piece.content
            }
            guard !visible.isEmpty else { continue }
            if plan.toolPolicy.requiresToolCall {
                guard ToolChoiceEnforcementPolicy.isFramingWhitespace(visible) else {
                    throw MultiModelBatchSchedulerEngineError.toolChoiceViolation(
                        "forced tool_choice produced visible text before a validated call")
                }
                continue
            }
            content += visible
            if streaming && !withholdsContent {
                events.append(.parsed(.init(content: visible, reasoningContent: nil)))
            }
        }
        // The caller emits these. Super's plan never sets
        // `strictCallsAsGenerated`, so a `strict` call is held to its schema
        // even once the response started, as on the withheld path.
        if !events.isEmpty { callRouter?.responseStarted = true }
        return events
    }

    /// The router's text: plain content stays a native content delta, never
    /// re-parsed for think markers downstream.
    private mutating func absorb(_ routed: [MLXServerGenerationEvent]) -> [MLXServerGenerationEvent] {
        routed.map { event in
            guard case .content(let text) = event else { return event }
            content += text
            return .parsed(.init(content: text, reasoningContent: nil))
        }
    }

    private static let frameOpenings = ["<tool_call>", "<function="]

    /// After route refused every mid-stream parse failure, a failure left at
    /// the end with a complete opening tag in its text is an unterminated
    /// frame; a bare `<to…` prefix was only withheld while being probed.
    private static func leavesUnterminatedFrame(_ handler: BatchedToolStreamHandler?, residual: String) -> Bool {
        (handler?.parseFailureCount ?? 0) > 0 && frameOpenings.contains(where: residual.contains)
    }

    /// The shared tagged-frame processor keeps text that precedes a `<` in the
    /// same chunk only until it returns; if the frame is still open, that text
    /// is lost. Starting every segment at a `<` leaves no such prefix.
    static func tagSegments(_ text: String) -> [String] {
        var segments: [String] = []
        var start = text.startIndex
        for index in text.indices where text[index] == "<" && index != start {
            segments.append(String(text[start..<index]))
            start = index
        }
        if start < text.endIndex { segments.append(String(text[start...])) }
        return segments
    }
}
