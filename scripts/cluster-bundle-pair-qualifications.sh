#!/bin/bash
# cluster-bundle-pair-qualifications.sh RECORDS.jsonl...
#
# Writes the provider's bundled pair-serving qualification records
# (provider-swift/Sources/ProviderCore/Inference/Distributed/Installed/
# DistributedInstalledPairQualificationRecords.swift) from record files that
# `darkbloom-cluster-pair-check record` wrote, one JSON line each. The grants
# a build carries are derived from exactly these lines
# (`ClusterPairServingDecisions`); nothing else names a model or a chip.
# Lines are kept as written, sorted and de-duplicated; a line that is not a
# single-line JSON object with the record schema is refused, and so is a set in
# which one artifact digest is recorded under unrelated registered models.
set -euo pipefail
[[ $# -ge 1 ]] || { echo "usage: $0 RECORDS.jsonl..." >&2; exit 2; }
repo="$(cd "$(dirname "$0")/.." && pwd)"
out="$repo/provider-swift/Sources/ProviderCore/Inference/Distributed/Installed/DistributedInstalledPairQualificationRecords.swift"
lines="$(cat "$@" | grep -v '^[[:space:]]*$' | LC_ALL=C sort -u)"
while IFS= read -r line; do
  [[ "$line" == '{'*'}' && "$line" == *'"schema":"darkbloom_cluster_pair_qualification_v1"'* && "$line" != *'"""#'* ]] \
    || { echo "not a qualification record line: ${line:0:120}" >&2; exit 1; }
done <<< "$lines"
# Refuse mislabelled artifact identities. The exact registered Gemma plain/8bit
# catalog aliases share all files but have distinct pinned manifests and runtime
# IDs (Gemma4RegisteredSpecification). Preserve each original record: this
# exception creates no record, renames no ID, and transfers no serving grant.
dupes="$(printf '%s\n' "$lines" | python3 -I -c 'import json, sys
aliases = {
    "a4722b6020adb1894c700b45ddcd58bc0e0f033abe7139f86cbbbfe60cba4eb6":
        {"registered_gemma4_26b", "registered_gemma4_26b_8bit"},
}
owners = {}
for line in sys.stdin:
    record = json.loads(line)
    owners.setdefault(record["artifactSHA256"], set()).add(record["runtimeModelID"])
print(" ".join(a[:12] + ":" + ",".join(sorted(m)) for a, m in sorted(owners.items()) if len(m) > 1 and not m.issubset(aliases.get(a, set()))))')"
[[ -z "$dupes" ]] || { echo "one artifact recorded under unrelated registered models (a mislabelled record): $dupes" >&2; exit 1; }
{
  echo '// Generated by scripts/cluster-bundle-pair-qualifications.sh from the qualification'
  echo '// runner'"'"'s records (`darkbloom-cluster-pair-check record`). Do not edit by hand: add'
  echo '// or remove records and run the script again.'
  echo ''
  echo '/// The cross-cable qualification records this build ships, one JSON line each.'
  echo '/// `ClusterPairServingGrants` derives every pair-serving grant from them.'
  echo 'enum ClusterPairQualificationRecordsBundled {'
  echo '    static let jsonLines = #"""'
  printf '%s\n' "$lines"
  echo '"""#'
  echo '}'
} > "$out"
echo "wrote $(printf '%s\n' "$lines" | wc -l | tr -d ' ') records to ${out#$repo/}"
