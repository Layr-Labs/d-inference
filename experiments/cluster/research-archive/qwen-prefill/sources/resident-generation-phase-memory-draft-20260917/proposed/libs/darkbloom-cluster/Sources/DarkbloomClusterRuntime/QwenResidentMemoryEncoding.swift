import Foundation

enum QwenResidentMemoryEncoding {
    static func encode(_ trace: QwenResidentMemoryTrace, into w: QwenGenerationPhaseJSON) throws {
        try w.key("memory"); try w.raw("{")
        try w.number("maximumSamples", QwenResidentMemoryRecorder.maximumSamples)
        try w.number("minimumPeriodicIntervalNanoseconds", QwenResidentMemoryRecorder.cadenceNanoseconds)
        try w.number("readyUptimeNanoseconds", trace.readyUptimeNanoseconds)
        try w.flag("sameProcessClockAsPhases", true)
        try w.flag("includesObserverOverhead", true)
        try w.flag("streamsSynchronizedForObservation", false)
        try w.flag("continuousOSPeakObserved", false)
        try w.flag("vmCategoriesAreDisjoint", false)
        try w.flag("preLoadSourceVerificationCovered", false)
        try w.flag("publicationAndModelReleaseCovered", false)
        try w.field("allocatorPeakScope", "process_cumulative_without_reset")
        try w.key("samples"); try w.raw("[")
        for (index, sample) in trace.samples.enumerated() {
            if index > 0 { try w.raw(",") }
            try w.raw("{"); try w.number("ordinal", index)
            try w.field("point", sample.point.rawValue)
            try w.number("startedNanoseconds", sample.startedNanoseconds)
            try w.number("completedNanoseconds", sample.completedNanoseconds)
            try w.number("osStartedNanoseconds", sample.osStartedNanoseconds)
            try w.number("osCompletedNanoseconds", sample.osCompletedNanoseconds)
            try w.number("physicalMemoryBytes", sample.physicalMemoryBytes)
            try w.number("pageSizeBytes", sample.pageSizeBytes)
            try w.number("kernelFreePages", sample.kernelFreePages)
            try w.number("freePages", sample.freePages)
            try w.number("inactivePages", sample.inactivePages)
            try w.number("speculativePages", sample.speculativePages)
            try w.number("actualFreeBytes", sample.actualFreeBytes)
            try w.number("estimatedReclaimableBytes", sample.estimatedReclaimableBytes)
            try w.number("pressureLevel", sample.pressureLevel)
            try w.number("swapUsedBytes", sample.swapUsedBytes)
            try w.number("activePages", sample.pages.active)
            try w.number("wiredPages", sample.pages.wired)
            try w.number("purgeablePages", sample.pages.purgeable)
            try w.number("fileBackedPages", sample.pages.fileBacked)
            try w.number("anonymousPages", sample.pages.anonymous)
            try w.number("compressorPages", sample.pages.compressor)
            try w.number("activeBytes", sample.activeBytes)
            try w.number("cacheBytes", sample.cacheBytes)
            try w.number("peakBytes", sample.peakBytes)
            try w.number("allocatorLimitBytes", sample.allocatorLimitBytes)
            try w.number("requiredActualFreeBytes", sample.requiredActualFreeBytes)
            try w.number("requiredAllocatorBytes", sample.requiredAllocatorBytes)
            try w.optionalNumber("authorizedTensorCount", sample.authorizedTensorCount)
            try w.optionalNumber("selectedTensorCount", sample.selectedTensorCount, comma: false)
            try w.raw("}")
        }
        try w.raw("]},")
    }
}
