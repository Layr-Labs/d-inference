"""Materialize P32/C16/O128/cut32 inputs for the existing qualification controller.

No SSH, native process, model load or expected output synthesis occurs here.
Ready templates must be generated by the adjacent exact-runtime metadata helper.
"""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import uuid
from configuration_inputs import absolute_path, digest, read_json, require, tokens

ARTIFACT = 'bbd0e0adcfe74e095073fefd0b9e116e4311d606ad9989cf81f8175e8ac18463'
CONFIGURATION = '4691da94a1b4ef415aad112ec46abebd33f8a41ad07380e486c0526eb945c1ff'
MANIFEST = 'd1239a5bc6d26d5ce4bf87f22270e3a703f4942e3d0d779948b4f65410df6dcc'
MODEL = 'registered_qwen38_27b'
PROFILE = dict(id='registered_qwen38_27b_greedy_generation_v1', vocabularySize=248_320,
               maximumPromptTokens=8192, maximumOutputTokens=128,
               maximumChunkTokens=512, maximumContextTokens=8320)


def metadata_templates(meta):
    require(meta['schema'] == 'qwen27b_owner_qualification_metadata_v1'
            and meta['modelID'] == MODEL and meta['artifactSHA256'] == ARTIFACT
            and meta['configurationSHA256'] == CONFIGURATION and meta['manifestSHA256'] == MANIFEST
            and type(meta['stageCut']) is int and meta['stageCut'] == 32
            and meta['canonicalCounts'] == [923, 924]
            and meta['activeBytes'] == [7_566_395_904, 7_566_406_144], 'Wrong native metadata')
    native = digest(meta['nativeBinarySHA256'])
    plan = digest(meta['planSHA256'])
    require(len(meta['readyTemplatesBase64']) == 2, 'Expected two templates')
    peers = None
    for rank, encoded in enumerate(meta['readyTemplatesBase64']):
        raw = base64.b64decode(encoded, validate=True)
        require(len(raw) <= 16_384 and raw.endswith(b'\n'), 'Template framing differs')
        frame = json.loads(raw)
        ready = frame['ready']
        identity = ready['identity']
        require(frame['version'] == 1 and frame['sequence'] == 0 and frame['kind'] == 'ready'
                and frame['membershipEpoch'] == '00000000-0000-0000-0000-000000000000'
                and identity['membershipEpoch'] == frame['membershipEpoch']
                and ready['rank'] == rank and ready['profile'] == PROFILE
                and identity['modelID'] == MODEL and identity['artifactSHA256'] == ARTIFACT
                and identity['configurationSHA256'] == CONFIGURATION
                and ready['executionPlanSHA256'] == plan and ready['requestCapacityBytes'] == 1,
                'Template does not match metadata')
        require(len(identity['peers']) == 2 and identity['peers'][0]['id'] != identity['peers'][1]['id']
                and all(p['buildSHA256'] == native for p in identity['peers']), 'Peer binding differs')
        require(peers is None or peers == identity['peers'], 'Rank peer bindings differ')
        peers = identity['peers']
    return meta['readyTemplatesBase64']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--metadata', required=True)
    parser.add_argument('--tokens', required=True, help='Exact root/reference tokenizer-derived JSON array of 32 IDs')
    parser.add_argument('--request', required=True, help='Pinned root request/tokenizer provenance JSON')
    parser.add_argument('--expected-ids', help='Qualified full-reference JSON array of 128 IDs; omitted for initial smoke')
    parser.add_argument('--native-sha256', required=True, help='Independently verified package binary pin')
    parser.add_argument('--install-root', required=True)
    parser.add_argument('--output', required=True, help='New local private configuration directory')
    parser.add_argument('--mode', required=True, choices=['ordinary', 'recording'])
    parser.add_argument('--request-id', required=True, help='Same request UUID as the independent reference')
    parser.add_argument('--epoch', required=True, help='Fresh membership UUID for these two owners')
    args = parser.parse_args()
    install = absolute_path(args.install_root)
    for text in (args.request_id, args.epoch):
        require(str(uuid.UUID(text)) == text and uuid.UUID(text).int != 0, 'Canonical nonzero UUID required')
    meta, meta_sha = read_json(args.metadata)
    templates = metadata_templates(meta)
    require(digest(args.native_sha256) == meta['nativeBinarySHA256'], 'Package/template binary pin differs')
    prompt, prompt_sha = read_json(args.tokens)
    tokens(prompt, 32)
    request, request_sha = read_json(args.request)
    require(request['model'] == MODEL and request['artifactSHA256'] == ARTIFACT
            and request['configurationSHA256'] == CONFIGURATION and request['manifestSHA256'] == MANIFEST
            and request['requestID'] == args.request_id and request['promptFileSHA256'] == prompt_sha
            and request['promptTokenIDsSHA256'] == hashlib.sha256(','.join(map(str, prompt)).encode()).hexdigest()
            and request['promptCount'] == 32 and request['chunkSize'] == 16
            and request['outputCount'] == 128 and request['stageCut'] == 32
            and request['stopTokenIDs'] == [] and request['mtp'] is False,
            'Request packet does not match the explicit short qualification')
    expected, expected_sha = None, None
    if args.expected_ids:
        expected, expected_sha = read_json(args.expected_ids)
        tokens(expected, 128)
    cluster = 'qwen27b-native-validation-' + args.epoch
    peers = [dict(host=host, user='gaj', port=22,
                  knownHostsFile='/Users/developer/.ssh/darkbloom_cluster_known_hosts',
                  identityFile='/Users/developer/.ssh/id_ed25519_darkbloom_cluster',
                  installedOwner=install + '/darkbloom-owner-qualification')
             for host in ('192.0.2.250', '192.0.2.223')]
    controller = dict(schema='darkbloom_owner_qualification_v1', cpuQualification=False,
        clusterID=cluster, readyTemplateBase64=templates[0], peers=peers,
        membershipEpoch=args.epoch, requestID=args.request_id, promptTokenIDs=prompt,
        stopTokenIDs=[], outputCount=128, chunkSize=16, expectedTokenIDs=expected,
        lifetimeSeconds=300, startupSeconds=90, requestSeconds=120)
    output = Path(args.output)
    output.mkdir(mode=0o700, exist_ok=False)
    def write(name, value):
        raw = (json.dumps(value, indent=2, sort_keys=True) + '\n').encode()
        fd = os.open(output / name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, 'wb') as stream:
            stream.write(raw)
    for rank in (0, 1):
        environment = dict(DARKBLOOM_BF16_WEIGHTS='1', DARKBLOOM_CBV2_ATTN_QUERY_BLOCK='128',
            MLX_ENABLE_TF32='1', JACCL_RANK=str(rank), JACCL_IBV_DEVICES=install + '/matrix.json',
            JACCL_COORDINATOR='169.254.70.46:51273', LANG='C', PATH='/usr/bin:/bin:/usr/sbin:/sbin')
        if args.mode == 'recording':
            environment.update(DARKBLOOM_BENCHMARK_PREFILL_POLICY='serial_v1',
                               DARKBLOOM_BENCHMARK_EVIDENCE_DIR=install + '/evidence')
        write(f'owner-rank{rank}.json', dict(schema='darkbloom_configured_worker_owner_v1',
            clusterID=cluster, workerExecutable=install + '/darkbloom-cluster-worker',
            modelDirectory='/Users/developer/DarkbloomDev/models/Qwen3.8-27B',
            leaseDirectory='/Users/developer/.darkbloom/cluster-device', stageCut=32,
            maximumLifetimeSeconds=300, workerEnvironment=environment, readyTemplateBase64=templates[rank]))
    write('controller.json', controller)
    write('matrix.json', [[None, 'rdma_en1'], ['rdma_en1', None]])
    write('input-provenance.json', dict(metadataSHA256=meta_sha, promptFileSHA256=prompt_sha,
        requestFileSHA256=request_sha,
        expectedIDsFileSHA256=expected_sha, nativeBinarySHA256=args.native_sha256,
        requestID=args.request_id, membershipEpoch=args.epoch, mode=args.mode,
        promptCount=32, chunkSize=16, outputCount=128, maximumTokens=160,
        expectedFinalCommittedInputs=159, stopTokenIDs=[], stageCut=32,
        knownHostsSHA256='e391f06908f452e59dee97b1a7a631d80c57d2844ddf7f4d8d0e78d2eb3d617a',
        numericalQualification=False, providerEligibilityEstablished=False))


if __name__ == '__main__':
    main()
