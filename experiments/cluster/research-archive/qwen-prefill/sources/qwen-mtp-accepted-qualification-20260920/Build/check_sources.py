"""Small closure checks only; does not inventory a workspace/cache or run a child."""
import ast
import hashlib
import json
from pathlib import Path

BASE = Path(__file__).resolve().parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    manifest = json.loads((BASE / 'manifest.json').read_bytes())
    for member in manifest['members']:
        path = BASE / member['path']
        if path.is_symlink() or path.stat().st_size != member['bytes'] or digest(path) != member['sha256']:
            raise ValueError('Build wrapper member changed: ' + str(path))
        if path.suffix == '.py':
            ast.parse(path.read_text())
    inputs = json.loads((BASE / 'inputs.json').read_bytes())
    for key in ['baseSource', 'baseDependencies', 'baseBuild', 'acceptedManifest', 'acceptedIntegration', 'referenceSnapshot', 'helper', 'referenceFixture']:
        pin = inputs[key]; path = Path(pin['path'])
        if path.stat().st_size != pin['bytes'] or digest(path) != pin['sha256']:
            raise ValueError('Authority changed: ' + key)
    base = json.loads(Path(inputs['baseSource']['path']).read_bytes())['members']
    deps = json.loads(Path(inputs['baseDependencies']['path']).read_bytes())['members']
    reference = json.loads(Path(inputs['referenceSnapshot']['path']).read_bytes())
    overlay = json.loads(Path(inputs['acceptedIntegration']['path']).read_bytes())['files']
    source = {x['path']: x['sha256'] for x in base}
    if len(source) != 3075 or len(deps) != 8755 or len(overlay) != 19 or len(inputs['referenceFiles']) != 397:
        raise ValueError('Closed source counts differ')
    for row in overlay:
        if source.get(row['path']) != row['beforeSHA256']:
            raise ValueError('Frozen overlay preimage does not join predecessor')
        source[row['path']] = row['sha256']
    for name, wanted in inputs['referenceFiles'].items():
        if name in source or reference[name] != wanted:
            raise ValueError('Reference source identity or disjointness differs')
        source[name] = wanted
    package = inputs['referencePackage']
    before = (BASE / 'reference-Package.original.swift').read_text()
    after = (BASE / 'reference-Package.swift').read_text()
    old = '        // Generated by build.sh: same pinned sources, real TCP ring enabled\n        // only for this experiment\'s explicit loopback correctness transport.\n        .package(path: ".generated-dependencies/mlx-swift"),'
    new = '        // Same final native MLX source as the paired MTP worker.\n        .package(path: "../../../libs/mlx-swift"),'
    if before.count(old) != 1 or before.replace(old, new) != after or digest(BASE / 'reference-Package.original.swift') != package['beforeSHA256'] or digest(BASE / 'reference-Package.swift') != package['afterSHA256']:
        raise ValueError('Reference package has more than the exact dependency path delta')
    source[package['path']] = package['afterSHA256']
    if len(source) != 3481 or digest(BASE / 'owned_process.py') != inputs['helper']['sha256']:
        raise ValueError('Projected closure or exact helper differs')
    print(json.dumps(dict(status='passed', wrapperMembers=len(manifest['members']), sourceBefore=3075,
                          sourceProjected=len(source), dependencies=8755, overlays=19, referencePackageMembers=397,
                          workspaceRead=False, compilerExecuted=False, modelExecuted=False, remoteExecuted=False), sort_keys=True))


if __name__ == '__main__':
    main()
